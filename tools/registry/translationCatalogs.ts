import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { RegistryItem } from 'shadcn/schema'
import ts from 'typescript'
import { buildRegistry } from './buildRegistry.ts'
import { ADDRESS_PREFIX, REPO_ROOT } from './layout.ts'

// Wrapper extraction policy, not a list of currently mounted components. Include
// composed Calendar and Context Selector alongside Working List and its UI deps.
const catalogs = [
    {
        name: 'workingListTranslationCatalog',
        roots: ['working-list', 'calendar', 'context-selector'],
    },
    { name: 'sidebarTranslationCatalog', roots: ['sidebar'] },
    {
        name: 'trackedEntityFinderTranslationCatalog',
        roots: ['tracked-entity-finder'],
    },
]

export const translationSourceFiles = (
    items: RegistryItem[],
    roots: string[]
): string[] => {
    const visited = new Set<string>()
    const files = new Set<string>()
    const visit = (name: string) => {
        if (visited.has(name)) return
        visited.add(name)
        const item = items.find((candidate) => candidate.name === name)
        if (!item) throw new Error(`Missing translation source item: ${name}`)
        for (const file of item.files ?? []) {
            if (/\.tsx?$/.test(file.path)) files.add(file.path)
        }
        for (const dependency of item.registryDependencies ?? []) {
            if (dependency.startsWith(ADDRESS_PREFIX)) {
                visit(dependency.slice(ADDRESS_PREFIX.length))
            }
        }
    }
    roots.forEach(visit)
    return [...files].sort()
}

const literal = (node: ts.Node | undefined): string | undefined =>
    node &&
    (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node))
        ? node.text
        : undefined

export const collectTranslationMarkers = (source: string): string[] => {
    const tree = ts.createSourceFile(
        'source.tsx',
        source,
        ts.ScriptTarget.Latest,
        true,
        ts.ScriptKind.TSX
    )
    const markers = new Set<string>()
    const visit = (node: ts.Node) => {
        if (ts.isCallExpression(node) || ts.isNewExpression(node)) {
            const callee = node.expression.getText(tree)
            const translated = ts.isCallExpression(node)
                ? ['i18n.t', 'translate', 't'].includes(callee)
                : callee === 'ValueParseError'
            const key = literal(node.arguments?.[0])
            if (translated && key !== undefined) {
                const options: Record<string, string> = {}
                const argument = node.arguments?.[1]
                if (argument && ts.isObjectLiteralExpression(argument)) {
                    for (const property of argument.properties) {
                        if (!ts.isPropertyAssignment(property)) continue
                        const name = ts.isIdentifier(property.name)
                            ? property.name.text
                            : literal(property.name)
                        if (name !== 'context' && name !== 'defaultValue')
                            continue
                        const value = literal(property.initializer)
                        if (value === undefined) {
                            throw new Error(
                                `Nonliteral translation ${name}: ${key}`
                            )
                        }
                        options[name] = value
                    }
                }
                // Runtime interpolation values are not extraction inputs. Keep
                // literal options without interpreting i18next's context syntax.
                const suffix = Object.keys(options).length
                    ? `, ${JSON.stringify(options)}`
                    : ''
                markers.add(`i18n.t(${JSON.stringify(key)}${suffix})`)
            }
        }
        ts.forEachChild(node, visit)
    }
    visit(tree)
    return [...markers].sort()
}

export const generateTranslationCatalogs = () => {
    const { items } = buildRegistry()
    return catalogs.map(({ name, roots }) => {
        const files = translationSourceFiles(items, roots)
        const markers = new Set(
            files.flatMap((file) =>
                collectTranslationMarkers(
                    readFileSync(join(REPO_ROOT, file), 'utf8')
                )
            )
        )
        const path = join(REPO_ROOT, `apps/web/src/${name}.ts`)
        const source = `import i18n from '@dhis2/d2-i18n'

// Generated by pnpm translations:write from ${roots.join(', ')} and registry dependencies.
// d2-app-scripts scans app-local literal calls; this marker is never invoked.
export const ${name} = () => [
${[...markers]
    .sort()
    .map((marker) => `    ${marker},`)
    .join('\n')}
]
`
        const content = execFileSync(
            join(REPO_ROOT, 'node_modules/.bin/oxfmt'),
            [`--stdin-filepath=${path}`],
            { input: source, encoding: 'utf8' }
        )
        return { path, content }
    })
}

if (
    process.argv[1] &&
    resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
    for (const { path, content } of generateTranslationCatalogs()) {
        if (process.argv.includes('--check')) {
            if (readFileSync(path, 'utf8') !== content) {
                throw new Error(`${path} is stale; run pnpm translations:write`)
            }
        } else {
            writeFileSync(path, content)
        }
    }
}
